#!/usr/bin/env node
// Regenerates the page from a Claude Design export of "Edukaan POS Page vN.dc.html".
//
//   node tools/sync-design.mjs "path/to/Edukaan POS Page v8.dc.html"
//
// Writes, verbatim from the design file:
//   template.js  — the page markup ({{ }} bindings, <sc-if>, <sc-for>), rendered by app.js
//   content.js   — every const after the Component class (COPY, DATA, LANG_LABELS, ISO, …)
//   design.css   — the <style> block from the design's <helmet>
// app.js holds the page logic (a port of the design's Component class) and is not generated.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) { console.error('usage: node tools/sync-design.mjs <design .dc.html>'); process.exit(1); }
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(src, 'utf8');

const cut = (from, to, start = 0) => {
  const a = html.indexOf(from, start);
  const b = html.indexOf(to, a + from.length);
  if (a < 0 || b < 0) throw new Error(`could not find ${from} … ${to}`);
  return { text: html.slice(a + from.length, b), end: b };
};

const helmet = cut('<helmet>', '</helmet>');
const style = /<style>([\s\S]*?)<\/style>/.exec(helmet.text);
if (!style) throw new Error('no <style> in <helmet>');
const template = cut('</helmet>', '</x-dc>').text.trim();

// Data consts follow the Component class inside the x-dc script.
const script = cut('data-dc-script', '</script>');
const body = script.text;
const classEnd = body.search(/\nconst [A-Z_]+ = /);
if (classEnd < 0) throw new Error('no data consts after the Component class');
const consts = body.slice(classEnd).trim();
const names = [...consts.matchAll(/^const (\w+) = /gm)].map(m => m[1]);

const banner = `// Generated by tools/sync-design.mjs from "${src.split('/').pop()}". Do not edit by hand; edit the design and re-sync.\n`;
writeFileSync(join(root, 'template.js'), `${banner}window.EDUKAAN_TEMPLATE = ${JSON.stringify(template)};\n`);
writeFileSync(join(root, 'content.js'), `${banner}${consts}\n\nObject.assign(window, { ${names.join(', ')} });\n`);
writeFileSync(join(root, 'design.css'), `/* Generated by tools/sync-design.mjs from the design's <helmet> styles. */\n${style[1].trim()}\n`);
console.log(`template.js ${template.length} chars · content.js consts: ${names.join(', ')} · design.css`);
